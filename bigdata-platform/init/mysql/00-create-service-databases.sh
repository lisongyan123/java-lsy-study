#!/usr/bin/env bash
set -euo pipefail

mysql_args=(-uroot -p"${MYSQL_ROOT_PASSWORD}")
if [[ -n "${MYSQL_HOST:-}" ]]; then
	mysql_args+=(--protocol=tcp -h "${MYSQL_HOST}")
fi

mysql "${mysql_args[@]}" <<SQL
CREATE DATABASE IF NOT EXISTS \`${ICEBERG_CATALOG_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${ICEBERG_CATALOG_USER}'@'%' IDENTIFIED BY '${ICEBERG_CATALOG_PASSWORD}';
ALTER USER '${ICEBERG_CATALOG_USER}'@'%' IDENTIFIED BY '${ICEBERG_CATALOG_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${ICEBERG_CATALOG_DATABASE}\`.* TO '${ICEBERG_CATALOG_USER}'@'%';

CREATE TABLE IF NOT EXISTS \`${ICEBERG_CATALOG_DATABASE}\`.iceberg_tables (
	catalog_name VARCHAR(255) NOT NULL,
	table_namespace VARCHAR(255) NOT NULL,
	table_name VARCHAR(255) NOT NULL,
	metadata_location VARCHAR(1000),
	previous_metadata_location VARCHAR(1000),
	PRIMARY KEY (catalog_name, table_namespace, table_name)
);
CREATE TABLE IF NOT EXISTS \`${ICEBERG_CATALOG_DATABASE}\`.iceberg_namespace_properties (
	catalog_name VARCHAR(255) NOT NULL,
	namespace VARCHAR(255) NOT NULL,
	property_key VARCHAR(255) NOT NULL,
	property_value VARCHAR(1000),
	PRIMARY KEY (catalog_name, namespace, property_key)
);

CREATE DATABASE IF NOT EXISTS \`${HIVE_METASTORE_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${HIVE_METASTORE_USER}'@'%' IDENTIFIED BY '${HIVE_METASTORE_PASSWORD}';
ALTER USER '${HIVE_METASTORE_USER}'@'%' IDENTIFIED BY '${HIVE_METASTORE_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${HIVE_METASTORE_DATABASE}\`.* TO '${HIVE_METASTORE_USER}'@'%';

CREATE DATABASE IF NOT EXISTS \`${OPENMETADATA_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${OPENMETADATA_DB_USER}'@'%' IDENTIFIED BY '${OPENMETADATA_DB_PASSWORD}';
ALTER USER '${OPENMETADATA_DB_USER}'@'%' IDENTIFIED BY '${OPENMETADATA_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${OPENMETADATA_DATABASE}\`.* TO '${OPENMETADATA_DB_USER}'@'%';
FLUSH PRIVILEGES;
SQL
